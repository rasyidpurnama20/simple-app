"""Timeline_Engine service layer.

All Timeline_Engine business logic lives here (Requirement 18.4): template
instantiation, the task-status state machine, hard/soft dependency handling,
fixed/relative deadline resolution, non-destructive schedule history, and the
Home next-best-work grouping. Views and cross-module callers depend only on
these methods and the returned DTOs; they never touch the ORM directly.
"""

