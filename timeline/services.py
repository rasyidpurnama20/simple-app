def _resolve_actor(actor) -> DemoUser | None:
    """Accept a DemoUser instance or an id and return the DemoUser (or None)."""
    if actor is None:
        return None
    if isinstance(actor, DemoUser):
        return actor
    return DemoUser.objects.filter(pk=actor).first()


def models_q_instance(instance_id):
    """Q object selecting schedule changes belonging to an instance."""
    from django.db.models import Q

    return Q(task__milestone__phase__instance_id=instance_id) | Q(
        milestone__phase__instance_id=instance_id
    )
