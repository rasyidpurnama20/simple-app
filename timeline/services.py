# Statuses that reflect explicit, in-progress user action. ``recompute_statuses``
# preserves these rather than overwriting them with derived readiness.
_ACTIVE_STATUSES = {
    TaskStatus.DIKERJAKAN,
    TaskStatus.DIAJUKAN,
    TaskStatus.PERLU_REVISI,
}


# ---------------------------------------------------------------------------
# Explanation helpers (guarantee the six-facet completeness of Property 13)
